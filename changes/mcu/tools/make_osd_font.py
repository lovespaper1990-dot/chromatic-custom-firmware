"""Build the menu font from fusion-pixel-8px-monospaced-zh_hans.bdf.

Source: TakWolf/fusion-pixel-font release 2026.11.10, 8px monospaced BDF.
Only the Chinese menu glyphs are included. Latin text uses fingfai.
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SIZE = 8


def read_glyphs(path, chars):
    bdf = path.read_text()
    if 'FAMILY_NAME "Fusion Pixel 8px Mono zh_Hans"' not in bdf:
        raise ValueError("Expected the 8px monospaced Simplified Chinese BDF")
    glyphs = {}
    for block in bdf.split("STARTCHAR ")[1:]:
        char = chr(int(re.search(r"^ENCODING (\d+)$", block, re.M)[1]))
        if char not in chars:
            continue
        width, height, x, y = map(int, re.search(r"^BBX (.+)$", block, re.M)[1].split())
        # BDF coordinates use the baseline; the source has ascent 7, descent 1.
        top = 7 - y - height
        rows = block.split("BITMAP\n", 1)[1].split("ENDCHAR", 1)[0].splitlines()
        if len(rows) != height or not (0 <= top <= SIZE - height and 0 <= x <= SIZE - width):
            raise ValueError(f"Invalid glyph bounds for {char}")
        cell = bytearray(SIZE)
        for row, bits in enumerate(rows, top):
            cell[row] = int(bits, 16) >> x
        glyphs[char] = cell
    missing = chars.difference(glyphs)
    if missing:
        raise ValueError(f"Missing menu glyphs: {sorted(missing)}")
    return glyphs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    messages = (ROOT / "components/common/osd_language.c").read_text()
    chars = sorted({ch for ch in messages if ord(ch) > 127})
    glyphs = read_glyphs(parser.parse_args().font, set(chars))
    first = ord(chars[0])
    bitmaps = []
    desc = ["    {0},"]
    offset = 0
    for ch in chars:
        pixels = glyphs[ch]
        bitmaps.append(f"    /* {ch} */")
        bitmaps.append("    " + ", ".join(f"0x{x:02x}" for x in pixels) + ",")
        desc.append(f"    {{.bitmap_index={offset}, .adv_w={16 * SIZE}, .box_w={SIZE}, .box_h={SIZE}, .ofs_y=-1}},")
        offset += len(pixels)
    lines = [
        "// Generated by tools/make_osd_font.py. Derived from Fusion Pixel 8px (zh_hans).",
        "// Copyright (c) 2022, TakWolf. See OSD-CJK-LICENSE.txt for font licenses.",
        '#include "lvgl.h"', "LV_FONT_DECLARE(fingfai);", "",
        "static const uint8_t pixels[] = {", *bitmaps, "};",
        "static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {", *desc, "};",
        "static const uint16_t codepoints[] = {",
    ]
    offsets = [str(ord(c) - first) for c in chars]
    for i in range(0, len(chars), 12):
        lines.append("    " + ", ".join(offsets[i:i + 12]) + ",")
    lines.extend([
        "};", "static const lv_font_fmt_txt_cmap_t cmap = {",
        f"    .range_start = {first}, .range_length = {ord(chars[-1]) - first + 1},",
        f"    .glyph_id_start = 1, .unicode_list = codepoints, .list_length = {len(chars)},",
        "    .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,", "};",
        "static lv_font_fmt_txt_glyph_cache_t cache;",
        "static const lv_font_fmt_txt_dsc_t descriptor = {",
        "    .glyph_bitmap = pixels, .glyph_dsc = glyphs, .cmaps = &cmap,",
        "    .cmap_num = 1, .bpp = 1, .cache = &cache,", "};",
        "const lv_font_t osd_cjk = {",
        "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
        "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
        "    .line_height = 9, .base_line = 2, .dsc = &descriptor, .fallback = &fingfai,",
        "};", "",
    ])
    (ROOT / "components/fonts/osd_cjk.c").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
