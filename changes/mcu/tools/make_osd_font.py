"""Build the menu's LVGL 8 font from Noto Sans CJK SC Regular with Pillow.

Usage: python tools/make_osd_font.py /path/to/NotoSansCJKsc-Regular.otf
Only ideographs used by osd_language.c are stored. Latin text uses fingfai.
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
SIZE = 10


def rasterize(font, character):
    if bytes(font.getmask(character)) == bytes(font.getmask(chr(0x10ffff))):
        raise ValueError(f"Source font lacks {character!r}")
    tile = Image.new("L", (SIZE, SIZE))
    draw = ImageDraw.Draw(tile)
    bounds = draw.textbbox((0, 0), character, font=font)
    draw.text((0, -bounds[1] + (SIZE - (bounds[3] - bounds[1])) // 2),
              character, font=font, fill=255)
    # Lift mid-tone coverage to keep thin strokes visible on the 160x144 LCD.
    levels = [round(15 * (x / 255) ** 0.72) for x in tile.tobytes()]
    return bytes((a << 4) | b for a, b in zip(levels[::2], levels[1::2]))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    font = ImageFont.truetype(str(parser.parse_args().font), SIZE)
    if font.getname() != ("Noto Sans CJK SC", "Regular"):
        raise ValueError("Use the SIL Open Font License Noto Sans CJK SC Regular source")
    messages = (ROOT / "components/common/osd_language.c").read_text()
    chars = sorted({ch for ch in messages if ord(ch) > 127})
    first = ord(chars[0])
    bitmaps = []
    desc = ["    {0},"]
    offset = 0
    for ch in chars:
        pixels = rasterize(font, ch)
        bitmaps.append(f"    /* {ch} */")
        for start in range(0, len(pixels), 10):
            bitmaps.append("    " + ", ".join(f"0x{x:02x}" for x in pixels[start:start + 10]) + ",")
        desc.append(f"    {{.bitmap_index={offset}, .adv_w={16 * SIZE}, .box_w={SIZE}, .box_h={SIZE}}},")
        offset += len(pixels)
    lines = [
        "// Generated by tools/make_osd_font.py. Derived from Noto Sans CJK SC Regular.",
        "// Copyright 2014-2021 Adobe. SIL Open Font License 1.1 (OSD-CJK-LICENSE.txt).",
        '#include "lvgl.h"', "LV_FONT_DECLARE(fingfai);", "",
        "static const uint8_t pixels[] = {", *bitmaps, "};",
        "static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {", *desc, "};",
        "static const uint16_t codepoints[] = {",
    ]
    offsets = [str(ord(c) - first) for c in chars]
    for i in range(0, len(chars), 12):
        lines.append("    " + ", ".join(offsets[i:i + 12]) + ",")
    lines.extend([
        "};", "static const lv_font_fmt_txt_cmap_t cmap = {",
        f"    .range_start = {first}, .range_length = {ord(chars[-1]) - first + 1},",
        f"    .glyph_id_start = 1, .unicode_list = codepoints, .list_length = {len(chars)},",
        "    .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,", "};",
        "static lv_font_fmt_txt_glyph_cache_t cache;",
        "static const lv_font_fmt_txt_dsc_t descriptor = {",
        "    .glyph_bitmap = pixels, .glyph_dsc = glyphs, .cmaps = &cmap,",
        "    .cmap_num = 1, .bpp = 4, .cache = &cache,", "};",
        "const lv_font_t osd_cjk = {",
        "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
        "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
        f"    .line_height = {SIZE}, .base_line = 0, .dsc = &descriptor, .fallback = &fingfai,",
        "};", "",
    ])
    (ROOT / "components/fonts/osd_cjk.c").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
